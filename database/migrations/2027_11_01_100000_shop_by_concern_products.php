    public function up(): void
    {
        if (! Schema::hasTable('categories') || ! Schema::hasTable('category_product') || ! Schema::hasTable('products')) {
            return;
        }

        // The live catalogue, or nothing. These lists were made from the 750
        // products on kbeautybliss.com; a shop carrying fewer than half of them
        // (a fresh install, the test database's sample products) is not the
        // shop they describe, and gets no categories and no links.
        $all = array_values(array_unique(array_merge(...array_column(self::CONCERNS, 'products'))));
        $present = DB::table('products')->whereIn('slug', $all)->count();

        if ($present * 2 < count($all)) {
            if (app()->runningInConsole()) {
                echo "Shop by Concern: {$present} of ".count($all)." listed products on this shop -- not the live catalogue, nothing changed.\n";
            }

            return;
        }

        $created = false;
        $report = [];

        foreach (self::CONCERNS as $concern) {
            $productIds = DB::table('products')->whereIn('slug', $concern['products'])->pluck('id')->all();

            $categoryId = $this->findCategory($concern['name'], $concern['find']);

            if ($categoryId === null) {
                // Never an empty category: on a shop without these products
                // (a fresh install, a test database) nothing is created.
                if ($productIds === []) {
                    $report[] = $concern['name'].': not on this shop, none of its products here -- skipped';
                    continue;
                }

                $categoryId = $this->createCategory($concern['name'], $concern['create']);
                $created = true;
            }

            $have = array_flip(DB::table('category_product')
                ->where('category_id', $categoryId)
                ->pluck('product_id')
                ->map(static fn ($id): int => (int) $id)
                ->all());

            $rows = [];

            foreach ($productIds as $id) {
                if (! isset($have[(int) $id])) {
                    $rows[] = ['category_id' => $categoryId, 'product_id' => (int) $id];
                }
            }

            foreach (array_chunk($rows, 200) as $chunk) {
                DB::table('category_product')->insertOrIgnore($chunk);
            }

            $report[] = sprintf('%s: %d listed, %d on the shop, %d added', $concern['name'],
                count($concern['products']), count($productIds), count($rows));
        }

        if ($created && class_exists(\App\Support\CategoryTree::class)) {
            \App\Support\CategoryTree::resync();
        }

        $this->flushCaches();

        if (app()->runningInConsole()) {
            echo implode("\n", $report)."\n";
        }
    }

