    private function findCategory(string $name, array $slugs): ?int
    {
        $id = DB::table('categories')->whereIn('slug', $slugs)
            ->orderByRaw('CASE slug '.implode(' ', array_map(
                static fn (int $i): string => 'WHEN ? THEN '.$i, array_keys($slugs))).' END', $slugs)
            ->value('id');

        if ($id !== null) {
            return (int) $id;
        }

        $want = self::normalise($name);

        foreach (DB::table('categories')->get(['id', 'name']) as $row) {
            if (self::normalise((string) $row->name) === $want) {
                return (int) $row->id;
            }
        }

        return null;
    }

    private function createCategory(string $name, string $slug): int
    {
        $base = $slug;
        $n = 2;

        while (DB::table('categories')->where('slug', $slug)->exists()) {
            $slug = $base.'-'.$n++;
        }

        $row = [
            'slug' => $slug,
            'name' => $name,
            'parent_id' => null,
            'position' => (int) DB::table('categories')->whereNull('parent_id')->max('position') + 1,
            'depth' => 0,
            'path' => $slug,
            'created_at' => now(),
            'updated_at' => now(),
        ];

        if (Schema::hasColumn('categories', 'short_url')) {
            $row['short_url'] = 1;
        }

        return (int) DB::table('categories')->insertGetId($row);
    }

    private static function normalise(string $name): string
    {
        return (string) preg_replace('/[^a-z0-9]+/', '', str_replace('&', 'and', strtolower(html_entity_decode($name))));
    }

    private function flushCaches(): void
    {
        if (method_exists(\App\Http\Controllers\Store\ShopController::class, 'flushSidebarCache')) {
            \App\Http\Controllers\Store\ShopController::flushSidebarCache();
        }

        if (class_exists(\App\Support\CategoryRollup::class)) {
            \App\Support\CategoryRollup::flush();
        }

        Cache::forget('kbb.home.cats');
        Cache::forget('kbb.home.rails');
    }
