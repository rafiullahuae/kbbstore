    /**
     * Write both files into the web root and return their stored paths.
     *
     * public_path(UgcMedia::DIR) and NOT a path of its own, so a demo clip
     * lives exactly where a real upload lives and is served by exactly the same
     * rule. On the live shop that is the WEB ROOT, which is a different
     * directory from the application root -- see bootstrap/app.php.
     *
     * Idempotent by content: the names are fixed, so seeding twice overwrites
     * rather than accumulating, and Demo Content's Remove deletes them through
     * the same UgcMedia::forget() a real clip uses.
     *
     * @return array{clip: string, poster: string}|null  null when the directory
     *                                                   cannot be written
     */
    public static function materialise(): ?array
    {
        $dir = public_path(\App\Services\UgcMedia::DIR);

        if (! is_dir($dir) && ! @mkdir($dir, 0755, true) && ! is_dir($dir)) {
            return null;
        }

        $clip = 'demo-clip.webm';
        $poster = 'demo-poster.jpg';

        if (@file_put_contents($dir.'/'.$clip, base64_decode(self::CLIP_B64, true)) === false) {
            return null;
        }

        if (@file_put_contents($dir.'/'.$poster, base64_decode(self::POSTER_B64, true)) === false) {
            return null;
        }

        return [
            'clip' => '/'.\App\Services\UgcMedia::DIR.'/'.$clip,
            'poster' => '/'.\App\Services\UgcMedia::DIR.'/'.$poster,
        ];
    }

    /** The byte length of the clip, for the row's `bytes` column. */
    public static function clipBytes(): int
    {
        return strlen((string) base64_decode(self::CLIP_B64, true));
    }

    /** The byte length of the poster. */
    public static function posterBytes(): int
    {
        return strlen((string) base64_decode(self::POSTER_B64, true));
    }
