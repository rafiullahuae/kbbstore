#!/usr/bin/env node
// KBB Studio — BUILD STEP (not run by the app): bundle the full flag-icons 4x3 SVG set (MIT, Panayiotis Lipiridis) for the
// capsules carousel, so every country's flag exists offline. Fetched once from the npm registry here, at build time; the
// app itself never goes on the network for a flag.
//
//   node tools/caps-flags.cjs            (needs `npm` and `tar` on the PATH)
//
// writes app/themes/capsules/flags-4x3.json  { v, version, flags: { code: "<svg…>" } }  (one file, whitespace-minified)
//        app/themes/capsules/countries.js     COUNTRIES = [[code, English name, group], …] grouped by continent, with the
//                                             Middle East as its own group
//        app/themes/capsules/LICENSE-flag-icons.txt
'use strict';
const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

const VERSION = '7.6.0';
const ROOT = path.resolve(__dirname, '..'), OUT = path.join(ROOT, 'app', 'themes', 'capsules');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'caps-flags-'));
execFileSync('npm', ['pack', `flag-icons@${VERSION}`, '--silent'], { cwd: tmp, stdio: ['ignore', 'pipe', 'inherit'] });
const tgz = fs.readdirSync(tmp).find((f) => f.endsWith('.tgz'));
const ex = path.join(tmp, 'x'); fs.mkdirSync(ex);
execFileSync('tar', ['xzf', path.join(tmp, tgz), '-C', ex]);
const PKG = path.join(ex, 'package');

// the Middle East as its own group (flag-icons files it under Asia / Africa)
const MIDDLE_EAST = new Set(['ae', 'sa', 'qa', 'kw', 'bh', 'om', 'ye', 'iq', 'ir', 'jo', 'lb', 'sy', 'ps', 'il', 'eg', 'tr']);
// places flag-icons leaves without a continent
const EXTRA = { xk: 'Europe', 'gb-eng': 'Europe', 'gb-sct': 'Europe', 'gb-wls': 'Europe', 'gb-nir': 'Europe', ic: 'Africa', 'sh-ac': 'Africa', 'sh-hl': 'Africa', 'sh-ta': 'Africa', dg: 'Asia', bv: 'Antarctica', hm: 'Antarctica', cp: 'North America', aq: 'Antarctica' };
// organisation flags kept as marks (eu = the Europe capsule); the rest (un, asean, …) are not countries
const MARKS = new Set(['eu']);
const SKIP = new Set(['xx', 'un', 'asean', 'cefta', 'eac', 'pc', 'arab', 'es-ct', 'es-ga', 'es-pv']);

const list = JSON.parse(fs.readFileSync(path.join(PKG, 'country.json'), 'utf8'));
const min = (s) => s.replace(/<!--[\s\S]*?-->/g, '').replace(/\s+id="flag-icons-[^"]*"/, '').replace(/>\s+</g, '><').replace(/\s{2,}/g, ' ').replace(/\n/g, ' ').trim();
const flags = {}, rows = [];
for (const c of list) {
  if (SKIP.has(c.code)) continue;
  const f = path.join(PKG, 'flags', '4x3', c.code + '.svg'); if (!fs.existsSync(f)) continue;
  flags[c.code] = min(fs.readFileSync(f, 'utf8'));
  if (MARKS.has(c.code)) continue;
  const g = MIDDLE_EAST.has(c.code) ? 'Middle East' : c.continent || EXTRA[c.code];
  if (!g) throw new Error('no group for ' + c.code);
  rows.push([c.code, c.name.replace('Türkiye', 'Turkey'), g]);
}
rows.sort((a, b) => a[1].localeCompare(b[1]));
fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(path.join(OUT, 'flags-4x3.json'), JSON.stringify({ v: 1, source: 'flag-icons ' + VERSION + ' (MIT) flags/4x3', flags }));
fs.copyFileSync(path.join(PKG, 'LICENSE'), path.join(OUT, 'LICENSE-flag-icons.txt'));
fs.writeFileSync(path.join(OUT, 'countries.js'), `// KBB Studio · capsules · every country with a flag in flags-4x3.json (flag-icons ${VERSION}, MIT), by continent.
// GENERATED by tools/caps-flags.cjs -- edit that script, not this file. [code, English name, group]
export const COUNTRY_GROUPS = ['Europe', 'Asia', 'Middle East', 'North America', 'South America', 'Africa', 'Oceania', 'Antarctica'];
export const COUNTRIES = [
${rows.map((r) => '  ' + JSON.stringify(r) + ',').join('\n')}
];
`);
fs.rmSync(tmp, { recursive: true, force: true });
console.log(`flags: ${Object.keys(flags).length} SVGs, ${(fs.statSync(path.join(OUT, 'flags-4x3.json')).size / 1024).toFixed(0)} KB · countries: ${rows.length}`);
