/** The <head> of a page. */
function spHead(string $path): string
{
    $html = (string) test()->get($path)->getContent();

    return preg_match('#<head>(.*?)</head>#s', $html, $m) === 1 ? $m[1] : '';
}

/** The head lines a search engine reads, in document order. */
function spHeadTags(string $path): array
{
    $out = [];

    foreach (preg_split('/\R/', spHead($path)) ?: [] as $line) {
        $line = trim($line);

        if ($line === '' || ! preg_match('#^<(title|meta|link)\b#', $line)) {
            continue;
        }

        // Only the tags that describe the page to a crawler; not the font
        // preconnects or the Vite tags, which are on every page and are not SEO.
        if (preg_match('#^<link#', $line) && ! preg_match('#rel="(canonical|alternate)"#', $line)) {
            continue;
        }

        if (preg_match('#^<meta (charset|name="viewport")#', $line)) {
            continue;
        }

        $out[] = $line;
    }

    return $out;
}

/** Every JSON-LD node in a page, decoded, in document order. */
function spNodes(string $path): array
{
    $html = (string) test()->get($path)->getContent();
    $out = [];

    preg_match_all('#<script type="application/ld\+json">(.*?)</script>#s', $html, $m);

    foreach ($m[1] as $json) {
        $decoded = json_decode($json, true);

        if (! is_array($decoded)) {
            continue;
        }

        foreach (array_is_list($decoded) ? $decoded : [$decoded] as $node) {
            if (is_array($node)) {
                $out[] = $node;
            }
        }
    }

    return $out;
}

function spNode(string $path, string $type): ?array
{
    foreach (spNodes($path) as $node) {
        if (($node['@type'] ?? null) === $type) {
            return $node;
        }
    }

    return null;
}

function spTypes(string $path): array
{
    return array_values(array_map(static fn (array $n): string => (string) ($n['@type'] ?? '?'), spNodes($path)));
}

/** Pretty JSON for the page, with the slashes readable. */
function spPretty(mixed $value): string
{
    return (string) json_encode($value, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
}

/** One matrix row. */
function spRow(string $area, string $claim, string $docSays, string $verdict, string $observed, string $where): array
{
    expect(['VERIFIED', 'STALE', 'MISSING', 'DELIBERATE', 'OWNER'])->toContain($verdict);

    return compact('area', 'claim', 'docSays', 'verdict', 'observed', 'where');
}

/** VERIFIED when the measurement holds, MISSING when it does not. */
function spCheck(bool $holds, string $verdict = 'VERIFIED'): string
{
    return $holds ? $verdict : 'MISSING';
}

