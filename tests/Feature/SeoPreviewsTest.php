/**
 * =============================================================================
 * THE SEO PREVIEW THE OWNER ASKED FOR, AND THE MATRIX BEHIND IT
 * =============================================================================
 *
 * Writes `docs/SEO-PREVIEWS.html`. Open it in a browser.
 *
 * ── WHY THIS IS A TEST AND NOT A SCRIPT ─────────────────────────────────────
 *
 * Four rounds of SEO work have been reported as done, and every report leans on
 * a document written at a point in time. `docs/SEO-GAP.md` still says
 * `LocalBusiness` is Missing; it has been built since round 2. It still says the
 * Journal index emits no `CollectionPage`; it has emitted one since round 4 was
 * merged. **A document is not evidence.** The owner's words for this round were
 * *"every single feature as per our research and final plan. don't skip or
 * assume on anything. give me previews also."*
 *
 * So the preview is generated by the suite, from the application's own HTTP
 * kernel, exactly as `docs/email-previews/*.html` are generated by
 * `OrderEmailPreviewsTest`. Every title, every meta tag, every JSON-LD node and
 * every byte of robots.txt, sitemap.xml and llms.txt on that page came out of a
 * real request made while this file ran. **Nothing on it is transcribed.** A
 * preview a human typed is a preview that stops matching the code the first time
 * somebody is in a hurry.
 *
 * ── AND THE MATRIX IS ASSERTED, NOT DESCRIBED ───────────────────────────────
 *
 * Every row of the feature matrix carries a verdict, and for every row whose
 * verdict is decidable by measurement the `verdict` is COMPUTED from the
 * observation and then asserted to equal the expected one. So a regression in
 * any of them turns this file red rather than quietly making the preview wrong.
 * The rows whose verdict is a judgement — the deliberate refusals, and the items
 * that are content rather than code — say so, carry the argument, and carry
 * today's measured numbers where the argument rests on a size.
 *
 * ── THE FIXTURE, AND WHY IT IS REAL DATA ────────────────────────────────────
 *
 * `storage/catalog/products.json` is the only real catalogue data in this
 * repository (22 products, all Beauty Devices and Makeup — see
 * docs/SEO-CONCERN-MAPPING.md §2). The preview's product is the Medicube Kojic
 * Acid Turmeric Booster Pro Set, read out of that file: its real name, real
 * price and sale price in fils, real SKU, real gallery and its own real
 * description. The article is the shop's real `heartleaf-extract-transforming-
 * k-beauty-skincare` slug and the content page is the real seeded `/faqs/` body.
 * The page says which commit and which fixtures it was generated from.
 */

/** Where the preview lands. */
function spPath(): string
{
    return base_path('docs/SEO-PREVIEWS.html');
}

/**
 * The store settings the preview is generated under.
 *
 * DELIBERATELY THIN. These are the values a shop cannot function without —
 * `site_url` and the site name — and nothing else. Every optional setting is
 * left at the value it ships at, because the point of the preview is to show
 * what the owner's shop emits TODAY, not what it could emit once eight boxes are
 * filled in. Where a setting changes the answer, the page shows both states
 * side by side and says which one is live.
 */
function spBaseSettings(array $extra = []): void
{
    foreach (array_merge([
        'site_url' => 'https://kbeautybliss.test',
        'seo_site_name' => 'K-Beauty Bliss',
        'seo_default_description' => 'Authentic Korean skincare, delivered across the UAE.',
    ], $extra) as $key => $value) {
        Setting::updateOrCreate(['key' => $key], ['value' => (string) $value, 'autoload' => true]);
    }

    Setting::flushMap();
    SettingsService::forgetMemo();
}

/** One product out of the real catalogue snapshot, by slug. */
function spCatalogRow(string $slug): array
{
    $rows = json_decode((string) file_get_contents(storage_path('catalog/products.json')), true);

    expect(is_array($rows))->toBeTrue('storage/catalog/products.json did not parse; the fixture claim on the preview would be false');

    foreach ($rows as $row) {
        if (is_array($row) && ($row['slug'] ?? null) === $slug) {
            return $row;
        }
    }

    throw new RuntimeException('storage/catalog/products.json has no product slugged ' . $slug);
}

